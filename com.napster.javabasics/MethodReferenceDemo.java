package com.napster.javabasics;

public class MethodReferenceDemo {

    public static void main(String args[]){

        String str = "Hello, World!";
        String str2 = "Java Method Reference";
        String str3 = "";

        boolean isStrBlank = str.isBlank();
        boolean isStr2Blank = str2.isBlank();
        boolean isStr3Blank = str3.isBlank();

        System.out.println("Is str blank? " + isStrBlank);
        System.out.println("Is str2 blank? " + isStr2Blank);
        System.out.println("Is str3 blank? " + isStr3Blank);





    }

}
